r"""Build the SEPA Payment File API demo for the website.

Writes the sample payment files to assets/demo/ (downloadable) and the engine's real validation reports to
_data/demos/sepa.json, which the product page renders. Run it with the SEPA project's own Python:

    ..\sepa-payment-api\.venv\Scripts\python _tools\build_sepa_demo.py

All names, IBANs and amounts in the samples are fictional (IBANs are standard test numbers).
"""
from __future__ import annotations

import json
import sys
from datetime import date, datetime
from pathlib import Path

SITE = Path(__file__).resolve().parents[1]
ENGINE = SITE.parent / "sepa-payment-api"
sys.path.insert(0, str(ENGINE))

from sepa.generate import generate  # noqa: E402
from sepa.validate import validate_bytes  # noqa: E402

OUT_FILES = SITE / "assets" / "demo"
OUT_DATA = SITE / "_data" / "demos" / "sepa.json"
TODAY = date(2026, 10, 21)  # fixed, so the samples' dates are not reported as past on later builds

TRANSFER = {
    "kind": "credit_transfer", "requested_date": "2026-10-23", "message_id": "PAYRUN-2026-10-23",
    "account_holder": {"name": "Acme GmbH", "iban": "DE89370400440532013000", "bic": "COBADEFFXXX",
                       "address": {"town": "Berlin", "country": "DE"}},
    "payments": [
        {"name": "Supplier BV", "iban": "NL91ABNA0417164300", "amount": "1234.56", "end_to_end_id": "INV-2026-17",
         "remittance": "Invoice 2026-17", "address": {"town": "Amsterdam", "country": "NL"}},
        {"name": "Office Supplies KG", "iban": "DE02120300000000202051", "amount": "49.50",
         "creditor_reference": "RF18539007547034"},
    ],
}

OLD = (ENGINE / "tests" / "fixtures" / "sct_v03_unstructured.xml").read_bytes()
BROKEN_DD = (ENGINE / "tests" / "fixtures" / "sdd_v02_sample.xml").read_bytes() \
    .replace(b"DE98ZZZ09999999999", b"DE98ZZZ09999999990") \
    .replace(b"<DtOfSgntr>2024-01-15</DtOfSgntr>", b"<DtOfSgntr>2026-12-01</DtOfSgntr>")

SAMPLES = [
    {"id": "valid", "title": "Valid transfer file", "file": "pain001-v09-valid.xml",
     "content": generate(TRANSFER, now=datetime(2026, 10, 21, 9, 0), today=TODAY)["xml"],
     "blurb": "A pain.001.001.09 credit transfer generated by the API: structured addresses, one invoice reference "
              "and one RF creditor reference. Every check passes."},
    {"id": "old", "title": "Old file, wrong total", "file": "pain001-v03-wrong-total.xml",
     "content": OLD.replace(b"<CtrlSum>1284.06</CtrlSum>", b"<CtrlSum>1248.06</CtrlSum>", 1),
     "blurb": "A 2009 pain.001.001.03 file whose header control sum has two digits swapped. A German bank may reject "
              "the whole file for this."},
    {"id": "dd", "title": "Direct debit, two errors", "file": "pain008-v02-errors.xml", "content": BROKEN_DD,
     "blurb": "A pain.008.001.02 direct debit with a mistyped creditor identifier and a mandate dated in the future."},
]
MAX_INPUT_LINES = 140


def main() -> None:
    OUT_FILES.mkdir(parents=True, exist_ok=True)
    OUT_DATA.parent.mkdir(parents=True, exist_ok=True)
    demos = []
    for s in SAMPLES:
        (OUT_FILES / s["file"]).write_bytes(s["content"])
        report = validate_bytes(s["content"], today=TODAY)
        text = s["content"].decode("utf-8")
        if text.count("\n") < 3:  # generated files are one line; indent them for reading
            import xml.dom.minidom
            text = xml.dom.minidom.parseString(s["content"]).toprettyxml(indent="  ")
            text = "\n".join(line for line in text.splitlines() if line.strip())
        lines = text.rstrip("\n").split("\n")
        demos.append({
            "id": s["id"], "title": s["title"], "blurb": s["blurb"], "file": s["file"], "size": len(s["content"]),
            "input": "\n".join(lines[:MAX_INPUT_LINES]), "input_truncated": len(lines) > MAX_INPUT_LINES,
            "message_type": report["message_type"], "valid": report["valid"],
            "error_count": report["error_count"], "warning_count": report["warning_count"],
            "summary": report["summary"], "issues": report["issues"],
            "json": json.dumps(report, indent=2, ensure_ascii=False),
        })
        print(f"{s['file']:30} {report['message_type']:16} valid={report['valid']} "
              f"errors={report['error_count']} warnings={report['warning_count']}")
    OUT_DATA.write_text(json.dumps(demos, indent=1, ensure_ascii=False), encoding="utf-8")


if __name__ == "__main__":
    main()
