r"""Build the NACHA/ACH demo for the website (part of the SEPA & NACHA Payment File API).

Writes the sample ACH files to assets/demo/ (downloadable), the engine's real validation reports to
_data/demos/ach.json (rendered on the ACH tool pages) and the return / change codes to _data/ach_codes.json.
Run it with the SEPA project's own Python:

    ..\sepa-payment-api\.venv\Scripts\python _tools\build_ach_demo.py

The payroll sample is fictional (made-up names, accounts, and routing numbers with a valid check digit).
The other samples are unmodified test files from the Moov ACH project (Apache-2.0); assets/demo/LICENSE-moov-ach.txt
is a copy of its license, which must stay next to them.
"""
from __future__ import annotations

import json
import sys
from datetime import date, datetime
from pathlib import Path

SITE = Path(__file__).resolve().parents[1]
ENGINE = SITE.parent / "sepa-payment-api"
sys.path.insert(0, str(ENGINE))

from ach import codes  # noqa: E402
from ach.generate import entries_from_csv, generate  # noqa: E402
from ach.layout import routing_check_digit  # noqa: E402
from ach.parse import read_returns  # noqa: E402
from ach.validate import validate_bytes  # noqa: E402

OUT_FILES = SITE / "assets" / "demo"
OUT_DATA = SITE / "_data" / "demos" / "ach.json"
OUT_CODES = SITE / "_data" / "ach_codes.json"
MOOV = ENGINE / "tests" / "fixtures" / "ach"
TODAY = date(2026, 10, 21)  # fixed, so the generated sample's date is not reported as past on later builds
MOOV_NOTE = " Test file from the open-source Moov ACH project (Apache-2.0), unmodified."


def routing(first8: str) -> str:
    return first8 + str(routing_check_digit(first8))


PAYROLL_CSV = (
    "name,routing,account,amount,account_type,addenda\n"
    f"Maria Lopez,{routing('12100035')},4400123456,1850.00,checking,October salary\n"
    f"Sam O'Brien,{routing('02200006')},77-1290,2310.45,savings,October salary\n"
    f"Lee Chen,{routing('06100015')},9100022,1675.20,checking,\n"
)
PAYROLL = {
    "immediate_destination": routing("07400001"), "immediate_destination_name": "Sample Bank",
    "immediate_origin": "1234567890", "immediate_origin_name": "Acme Payroll Inc",
    "company_name": "Acme Payroll", "company_id": "1234567890", "sec_code": "PPD", "description": "PAYROLL",
    "effective_date": "2026-10-23", "entries": entries_from_csv(PAYROLL_CSV),
}

SAMPLES = [
    {"id": "payroll", "title": "Payroll from CSV", "file": "ach-ppd-payroll.ach",
     "content": generate(PAYROLL, today=TODAY, now=datetime(2026, 10, 21, 9, 0))["ach"],
     "blurb": "A PPD payroll file (three credits) generated by the API from a three-line CSV. Every check passes. "
              "Names, accounts and routing numbers are made up."},
    {"id": "debit", "title": "PPD debit (Moov)", "file": "ach-ppd-debit-moov.ach",
     "content": (MOOV / "ppd-debit.ach").read_bytes(),
     "blurb": "A PPD debit file written by an independent ACH library. Structure and totals pass; two lines without "
              "their trailing spaces and the old effective date are reported as warnings." + MOOV_NOTE},
    {"id": "check-digit", "title": "Wrong check digit (Moov)", "file": "ach-ppd-wrong-check-digit-moov.ach",
     "content": (MOOV / "ppd-debit-invalid-entryDetail-checkDigit.ach").read_bytes(),
     "blurb": "The same kind of file with a wrong routing check digit in the entry: the receiving bank would return "
              "it (R28)." + MOOV_NOTE},
    {"id": "return", "title": "Return file (Moov)", "file": "ach-return-web-moov.ach",
     "content": (MOOV / "return-WEB.ach").read_bytes(), "returns": True,
     "blurb": "A file of returned WEB debits, as a bank sends it back. The API's returns endpoint lists each return "
              "with its code explained." + MOOV_NOTE},
]


def main() -> None:
    OUT_FILES.mkdir(parents=True, exist_ok=True)
    demos = []
    for s in SAMPLES:
        (OUT_FILES / s["file"]).write_bytes(s["content"])
        report = validate_bytes(s["content"], today=TODAY)
        text = s["content"].decode("ascii").replace("\r\n", "\n").rstrip("\n")
        demo = {
            "id": s["id"], "title": s["title"], "blurb": s["blurb"], "file": s["file"], "size": len(s["content"]),
            "input": text, "valid": report["valid"],
            "error_count": report["error_count"], "warning_count": report["warning_count"],
            "summary": report["summary"], "issues": report["issues"],
            "json": json.dumps(report, indent=2, ensure_ascii=False),
        }
        if s.get("returns"):
            demo["returns_json"] = json.dumps(read_returns(s["content"]), indent=2, ensure_ascii=False)
        demos.append(demo)
        print(f"{s['file']:36} valid={report['valid']} errors={report['error_count']} "
              f"warnings={report['warning_count']} {[i['rule'] for i in report['issues']]}")
    OUT_DATA.write_text(json.dumps(demos, indent=1, ensure_ascii=False), encoding="utf-8")
    OUT_CODES.write_text(json.dumps({
        "returns": [{"code": c, "title": t, "explanation": e, "action": a, "retry": c in codes.RETRY_ALLOWED}
                    for c, (t, e, a) in codes.RETURN_CODES.items()],
        "changes": [{"code": c, "title": t, "fields": [f[0].replace("_", " ") for f in fields]}
                    for c, (t, fields) in codes.CHANGE_CODES.items()],
        "noc_action": codes.NOC_ACTION,
    }, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"PAYROLL CSV:\n{PAYROLL_CSV}")


if __name__ == "__main__":
    main()
